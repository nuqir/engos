// Универсальная функция добавления упражнений

window.addNNExercise = function(exercise, rows) {

 const tasks = rows.map(function(row,index){

  const [pattern, answer, ruleCode, word, detail] = row;

  const fullWord = pattern.replace("{}",answer);

  const dictionaryWord = word || fullWord.toLowerCase();

  const explanation =
   "Правильно: " + fullWord + ". " +
   (window.NN_EXPLANATIONS[ruleCode] || "") +
   (detail ? " " + detail : "");

  return {

   id: "alexandrova-nn-" +
    String(exercise).padStart(3,"0") + "-" +
    String(index+1).padStart(3,"0"),

   topic: "nn",

   exercise: exercise,

   pattern: pattern,

   instruction: "Выберите Н или НН.",

   blanks: [{

    answer: answer,

    options: ["н","нн"],

    rule: "nn",

    name: "Правописание Н и НН",

    explanation: explanation,

    checkWord: dictionaryWord

   }],

   links: [{

    label: dictionaryWord + " — Викисловарь",

    url: "https://ru.wiktionary.org/wiki/" +
     encodeURIComponent(dictionaryWord),

    note: "Проверка написания слова"

   }]

  };

 });

 const existingIds = new Set(
  window.ORTHO_DATA.map(task => task.id)
 );

 window.ORTHO_DATA.push(
  ...tasks.filter(task => !existingIds.has(task.id))
 );

};


