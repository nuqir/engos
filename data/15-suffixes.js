window.addSuffixExercise = function(exercise, rows){

 const tasks = rows.map(function(row,index){

  const [source,codes,lemmas,details] = row;

  const answers = Array.from(
   source.matchAll(/\{([а-яё]*)\}/gi)
  ).map(m => m[1]);

  const pattern = source.replace(
   /\{[а-яё]*\}/gi,"{}"
  );

  const fullWord = source.replace(/[{}]/g,"");

  const ruleList = codes.split("|");
  const lemmaList = lemmas.split("|");
  const detailList = (details || "").split("|");

  if(
   answers.length !== ruleList.length ||
   answers.length !== lemmaList.length
  ){
   throw new Error(
    "Ошибка количества пропусков: " + source
   );
  }

  const blanks = answers.map(function(answer,i){

   const code = ruleList[i];
   const rule = window.SUFFIX_RULES[code];

   if(!rule){
    throw new Error("Неизвестное правило: " + code);
   }

   let options;

   if(["CH","SH"].includes(code)){
    options = ["ч","щ"];
   } else if(
    ["K","SK","SKEX","SKSOFT","SKL","SKN"].includes(code)
   ){
    options = ["с","ьс","ь",""];
   } else if(["е","и"].includes(answer)){
    options = ["е","и","ы","я"];
   } else if(["о","е","ы","и","у","ю","а","я","ё"].includes(answer)){
    options = ["а","о","е","и","ы","у","ю","я","ё"];
   } else if(["ь",""].includes(answer)){
    options = ["ь",""];
   } else {
    options = ["н","нн","с","ч","щ","ь",""];
   }

   if(!options.includes(answer)){
    options.push(answer);
   }

   return {

    answer: answer,
    options: options,

    rule: "suffixes-" + code,
    name: rule.title,

    explanation:
     "Правильно: " + fullWord + ". " +
     (answer === ""
      ? "Дополнительная буква не требуется. "
      : "Пишется " + answer.toUpperCase() + ". ") +
     rule.text + " " +
     (detailList[i] || ""),

    checkWord: ""

   };

  });

  const links = [...new Set(lemmaList)].map(word => ({

   label: word + " — Викисловарь",

   url: "https://ru.wiktionary.org/wiki/" +
    encodeURIComponent(word),

   note: "Проверка написания и строения слова"

  }));

  return {

   id: "alexandrova-15-" +
    String(exercise).padStart(3,"0") + "-" +
    String(index+1).padStart(3,"0"),

   topic: "suffixes",
   exercise: exercise,
   pattern: pattern,

   instruction:
    "Вставьте пропущенные буквы. Определите часть речи и суффикс.",

   blanks: blanks,
   links: links

  };

 });

 const existingIds = new Set(
  window.ORTHO_DATA.map(t => t.id)
 );

 window.ORTHO_DATA.push(
  ...tasks.filter(t => !existingIds.has(t.id))
 );

};


