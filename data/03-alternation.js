// ==================================================
// УНИВЕРСАЛЬНАЯ ФУНКЦИЯ
// ==================================================

window.addAlternationExercise = function(exercise,rows){

 const tasks = rows.map(function(row,index){

  const [pattern,answer,ruleId,detail,word] = row;

  const rule = window.ALT_RULES[ruleId];

  if(!rule){
   throw new Error("Неизвестное правило: " + ruleId);
  }

  const fullWord = pattern.replace("{}",answer);

  const dictionaryWord =
   word || fullWord.toLowerCase();

  let options;

  if(["а","о"].includes(answer)){
   options = ["а","о"];
  } else if(["е","и"].includes(answer)){
   options = ["е","и"];
  } else {
   options = ["а","о","е","и","ы"];
  }

  if(ruleId === "plav-plov"){
   options = ["а","о","ы"];
  }

  return {

   id: "alexandrova-03-" +
    String(exercise).padStart(3,"0") + "-" +
    String(index+1).padStart(3,"0"),

   topic: "alternation",

   exercise: exercise,

   pattern: pattern,

   instruction: "Вставьте пропущенную гласную.",

   blanks: [{

    answer: answer,

    options: options,

    rule: ruleId,

    name: rule.title,

    explanation:
     "Правильно: " + fullWord + ". " +
     detail + " Правило: " + rule.text,

    checkWord: ""

   }],

   links: [{

    label: dictionaryWord + " — Викисловарь",

    url: "https://ru.wiktionary.org/wiki/" +
     encodeURIComponent(dictionaryWord),

    note: "Проверка написания слова"

   }]

  };

 });

 const existingIds = new Set(
  window.ORTHO_DATA.map(task => task.id)
 );

 window.ORTHO_DATA.push(
  ...tasks.filter(task => !existingIds.has(task.id))
 );

};


