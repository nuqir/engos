window.ORTHO_DATA = window.ORTHO_DATA || [];

window.addCheckedExercise = function(exercise, rows) {

 const options = [
  "а", "о", "е", "и", "я",
  "ы", "у", "ю", "ё", "э"
 ];

 const dictionaryURL = function(word) {
  return "https://ru.wiktionary.org/wiki/" +
   encodeURIComponent(
    word.normalize("NFD")
    .replace(/\u0301/g, "")
    .normalize("NFC")
    .toLowerCase()
   );
 };

 const tasks = rows.map(function(row, index) {

  const [pattern, answers, words, explanations] = row;

  const answerList = answers.split("|");
  const wordList = words.split("|");

  const explanationList = explanations
   ? explanations.split("|")
   : [];

  const blanks = answerList.map(function(answer, i) {

   const checkWord = wordList[i];

   return {
    answer: answer,
    options: options,
    rule: "checked",
    name: "Проверяемая безударная гласная",
    explanation: explanationList[i] ||
     "Пишется буква " + answer.toUpperCase() +
     ". Проверочное слово — " + checkWord +
     ". В проверочном слове соответствующая гласная находится под ударением.",
    checkWord: checkWord
   };

  });

  const links = wordList.map(function(word) {
   return {
    label: word + " — Викисловарь",
    url: dictionaryURL(word),
    note: "Проверочное слово"
   };
  });

  const task = {
   id: "alexandrova-01-" +
    String(exercise).padStart(3, "0") + "-" +
    String(index + 1).padStart(3, "0"),
   topic: "checked",
   exercise: exercise,
   pattern: pattern,
   instruction: "Вставьте пропущенные буквы.",
   blanks: blanks,
   links: links
  };

  const blankCount = (pattern.match(/\{\}/g) || []).length;

  if (blankCount !== blanks.length) {
   throw new Error("Ошибка в задании " + task.id);
  }

  return task;

 });

 const existingIds = new Set(
  window.ORTHO_DATA.map(task => task.id)
 );

 window.ORTHO_DATA.push(
  ...tasks.filter(task => !existingIds.has(task.id))
 );

};


