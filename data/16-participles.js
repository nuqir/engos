window.addParticiplesExercise = function(exercise,rows){

 const tasks = rows.map(function(row,index){

  const [source,code,verb,detail] = row;

  const match = source.match(/\{([а-яё]+)\}/i);

  if(!match){
   throw new Error("Не найден пропуск: "+source);
  }

  const answer = match[1];

  const pattern = source.replace(
   /\{[а-яё]+\}/gi,"{}"
  );

  const fullWord = source.replace(/[{}]/g,"");

  const rule = window.PARTICIPLE_RULES[code];

  if(!rule){
   throw new Error("Неизвестное правило: "+code);
  }

  const options = [...rule.options];

  if(!options.includes(answer)){
   options.push(answer);
  }

  return {

   id:"alexandrova-16-"+
    String(exercise).padStart(3,"0")+"-"+
    String(index+1).padStart(3,"0"),

   topic:"participles",

   exercise:exercise,

   pattern:pattern,

   instruction:
    "Вставьте пропущенную букву в суффиксе причастия.",

   blanks:[{

    answer:answer,

    options:options,

    rule:"participles-"+code,

    name:rule.title,

    explanation:
     "Правильно: "+fullWord+". "+
     "Производящий глагол: "+verb+". "+
     rule.text+" "+
     (detail || ""),

    checkWord:""

   }],

   links:[{

    label:verb+" — Викисловарь",

    url:"https://ru.wiktionary.org/wiki/"+
     encodeURIComponent(verb),

    note:"Производящий глагол и его грамматические формы"

   }]

  };

 });

 const existingIds = new Set(
  window.ORTHO_DATA.map(t=>t.id)
 );

 window.ORTHO_DATA.push(
  ...tasks.filter(t=>!existingIds.has(t.id))
 );

};

