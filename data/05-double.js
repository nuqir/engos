window.addDoubleExercise = function(exercise, rows){

 const tasks = rows.map(function(row,index){

  const [source,detail,word] =
   typeof row === "string" ? [row] : row;

  const matches = Array.from(
   source.matchAll(/\{([а-яё]+)\}/gi)
  );

  const answers = matches.map(m => m[1]);

  const pattern = source.replace(
   /\{([а-яё]+)\}/gi,
   "{}"
  );

  const fullWord = source.replace(
   /[{}]/g,
   ""
  );

  const dictionaryWord =
   word || fullWord.toLowerCase();

  return {

   id: "alexandrova-05-" +
    String(exercise).padStart(3,"0") + "-" +
    String(index+1).padStart(3,"0"),

   topic: "double",

   exercise: exercise,

   pattern: pattern,

   instruction: "Выберите правильное написание.",

   blanks: answers.map(function(answer,i){

    const letter = answer[0];

    const explanation = Array.isArray(detail)
     ? detail[i]
     : detail;

    return {

     answer: answer,

     options: [letter,letter+letter],

     rule: "double",

     name: "Двойные согласные",

     explanation:
      "Правильно: " + fullWord + ". " +
      "В пропуске № " + (i+1) +
      " пишется " + answer.toUpperCase() +
      ". " +
      (explanation ||
       "Словарное написание. Необходимо запомнить."),

     checkWord: ""

    };

   }),

   links: [{

    label: dictionaryWord + " — Викисловарь",

    url: "https://ru.wiktionary.org/wiki/" +
     encodeURIComponent(dictionaryWord),

    note: "Словарная проверка написания"

   }]

  };

 });

 const existingIds = new Set(
  window.ORTHO_DATA.map(task => task.id)
 );

 window.ORTHO_DATA.push(
  ...tasks.filter(task => !existingIds.has(task.id))
 );

};


