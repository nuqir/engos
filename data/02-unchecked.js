window.addUncheckedExercise = function(exercise, rows) {

 const options = [
  "а","о","е","и","я",
  "ы","у","ю","ё","э"
 ];

 const tasks = rows.map(function(row,index){

  const [pattern,answers,word,detail] = row;

  const answerList = answers.split("|");

  let position = 0;

  const fullWord = pattern.replace(
   /\{\}/g,
   () => answerList[position++]
  );

  const dictionaryWord = word ||
   fullWord.toLowerCase();

  const blankCount =
   (pattern.match(/\{\}/g) || []).length;

  if(blankCount !== answerList.length){

   throw new Error(
    "Ошибка количества пропусков: " + pattern
   );

  }

  return {

   id: "alexandrova-02-" +
    String(exercise).padStart(3,"0") + "-" +
    String(index+1).padStart(3,"0"),

   topic: "unchecked",

   exercise: exercise,

   pattern: pattern,

   instruction: "Вставьте пропущенные буквы.",

   blanks: answerList.map(function(answer,i){

    return {

     answer: answer,

     options: options,

     rule: "unchecked",

     name: "Непроверяемая безударная гласная",

     explanation:
      "Правильное написание: " + fullWord +
      ". В пропуске № " + (i+1) +
      " пишется буква " +
      answer.toUpperCase() +
      ". " +
      (detail ||
       "Написание необходимо запомнить и проверять по словарю."),

     checkWord: ""

    };

   }),

   links: [{

    label: dictionaryWord + " — Викисловарь",

    url: "https://ru.wiktionary.org/wiki/" +
     encodeURIComponent(dictionaryWord),

    note: "Словарная проверка написания"

   }]

  };

 });

 const existingIds = new Set(
  window.ORTHO_DATA.map(task => task.id)
 );

 window.ORTHO_DATA.push(
  ...tasks.filter(task => !existingIds.has(task.id))
 );

};


