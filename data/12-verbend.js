window.addVerbendExercise = function(exercise, rows){

 const tasks = rows.map(function(row,index){

  const [source,codes,lemma,details] = row;

  const answers = Array.from(
   source.matchAll(/\{([а-яё]*)\}/gi)
  ).map(m => m[1]);

  const pattern = source.replace(
   /\{[а-яё]*\}/gi,"{}"
  );

  const fullWord = source.replace(/[{}]/g,"");

  const ruleList = codes.split("|");
  const detailList = (details || "").split("|");

  if(answers.length !== ruleList.length){
   throw new Error(
    "Ошибка количества пропусков: " + source
   );
  }

  const blanks = answers.map(function(answer,i){

   const code = ruleList[i];
   const rule = window.VERBEND_RULES[code];

   if(!rule){
    throw new Error("Неизвестное правило: " + code);
   }

   let options;

   if(["ь",""].includes(answer)){
    options = ["ь",""];
   } else if(["е","и","ё"].includes(answer)){
    options = ["е","и","ё"];
   } else if(["у","ю","а","я"].includes(answer)){
    options = ["у","ю","а","я"];
   } else {
    options = ["е","и","ё","у","ю","а","я"];
   }

   return {

    answer: answer,
    options: options,

    rule: "verbend-" + code,
    name: rule.title,

    explanation:
     "Правильно: " + fullWord + ". " +
     "Начальная форма: " + lemma + ". " +
     (answer === ""
      ? "Мягкий знак не пишется. "
      : "Пишется " + answer.toUpperCase() + ". ") +
     rule.text + " " +
     (detailList[i] || ""),

    checkWord: ""

   };

  });

  const links = [{
   label: lemma + " — Викисловарь",
   url: "https://ru.wiktionary.org/wiki/" +
    encodeURIComponent(lemma),
   note: "Начальная форма и таблица спряжения"
  }];

  return {

   id: "alexandrova-12-" +
    String(exercise).padStart(3,"0") + "-" +
    String(index+1).padStart(3,"0"),

   topic: "verbend",
   exercise: exercise,
   pattern: pattern,

   instruction:
    "Вставьте пропущенные буквы. Определите форму глагола.",

   blanks: blanks,
   links: links

  };

 });

 const existingIds = new Set(
  window.ORTHO_DATA.map(t => t.id)
 );

 window.ORTHO_DATA.push(
  ...tasks.filter(t => !existingIds.has(t.id))
 );

};


