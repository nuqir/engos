// {S} — слитно
// {H} — через дефис
// {R} — раздельно

window.addCompoundsExercise = function(exercise,rows){

 const separators={
  S:"",
  H:"-",
  R:" "
 };

 const labels={
  S:"слитно",
  H:"через дефис",
  R:"раздельно"
 };

 const tasks=rows.map(function(row,index){

  const [source,codes,lemma,details]=row;

  const markers=Array.from(
   source.matchAll(/\{([SHR])\}/g)
  ).map(m=>m[1]);

  const ruleList=codes.split("|");

  const detailList=(details||"").split("|");

  if(markers.length!==ruleList.length){
   throw new Error(
    "Ошибка количества пропусков: "+source
   );
  }

  const pattern=source.replace(
   /\{[SHR]\}/g,"{}"
  );

  const fullWord=source.replace(
   /\{([SHR])\}/g,
   (_,marker)=>separators[marker]
  );

  const blanks=markers.map(function(marker,i){

   const code=ruleList[i];

   const rule=window.COMPOUND_RULES[code];

   if(!rule){
    throw new Error("Неизвестное правило: "+code);
   }

   return {

    answer:separators[marker],

    options:["","-"," "],

    rule:"compounds-"+code,

    name:rule.title,

    explanation:
     "Правильно: "+fullWord+". "+
     "Пишется "+labels[marker]+". "+
     rule.text+" "+
     (detailList[i]||""),

    checkWord:""

   };

  });

  const dictionaryWords=lemma.split("|");

  return {

   id:"alexandrova-18-"+
    String(exercise).padStart(3,"0")+"-"+
    String(index+1).padStart(3,"0"),

   topic:"compounds",

   exercise:exercise,

   pattern:pattern,

   instruction:
    "Выберите слитное, дефисное или раздельное написание.",

   blanks:blanks,

   links:dictionaryWords.map(word=>({

    label:word+" — Викисловарь",

    url:"https://ru.wiktionary.org/wiki/"+
     encodeURIComponent(word),

    note:"Словарная проверка написания"

   }))

  };

 });

 const existingIds=new Set(
  window.ORTHO_DATA.map(t=>t.id)
 );

 window.ORTHO_DATA.push(
  ...tasks.filter(t=>!existingIds.has(t.id))
 );

};

