// Универсальная функция для разделов 20 и 21

window.addSpellingExercise=function(
 topic,section,exercise,rows
){

 const marks={
  S:"",
  R:" ",
  H:"-",
  N:""
 };

 const tasks=rows.map((row,index)=>{

  const [source,lemma,explanation]=row;

  const answers=Array.from(
   source.matchAll(/\{([^{}]*)\}/g)
  ).map(m=>m[1]);

  const pattern=source.replace(
   /\{[^{}]*\}/g,"{}"
  );

  const blanks=answers.map(mark=>{

   const answer=Object.prototype.hasOwnProperty.call(
    marks,mark
   )?marks[mark]:mark;

   let options;

   if(["S","R","H"].includes(mark)){
    options=[""," ","-"];
   }else if(mark==="ь" || mark==="N"){
    options=["ь",""];
   }else if(["а","о"].includes(mark)){
    options=["а","о"];
   }else if(["е","и"].includes(mark)){
    options=["е","и"];
   }else{
    options=[answer];
   }

   return {
    answer,
    options,
    inputType:"choice",
    rule:topic,
    name:window.ORTHO_RULES[topic].title,
    explanation,
    checkWord:""
   };

  });

  return {
   id:"alexandrova-"+section+"-"+
    String(exercise).padStart(3,"0")+"-"+
    String(index+1).padStart(3,"0"),
   topic,
   exercise,
   pattern,
   instruction:
    "Вставьте буквы или выберите способ написания.",
   blanks,
   links:lemma.split("|").map(word=>({
    label:word+" — Викисловарь",
    url:"https://ru.wiktionary.org/wiki/"+
     encodeURIComponent(word),
    note:"Проверка написания и значения"
   }))
  };

 });

 const ids=new Set(
  window.ORTHO_DATA.map(t=>t.id)
 );

 window.ORTHO_DATA.push(
  ...tasks.filter(t=>!ids.has(t.id))
 );

};

if(!window.ORTHO_TOPICS.some(t=>t.id==="adverbs")){
 window.ORTHO_TOPICS.push({
  id:"adverbs",
  title:"Правописание наречий и соотносимых с ними словоформ других частей речи",
  page:89
 });
}

