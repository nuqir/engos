window.addConsonantsExercise = function(exercise, rows) {

 const pairs = {
  "б":"п", "п":"б",
  "в":"ф", "ф":"в",
  "г":"к", "к":"г",
  "д":"т", "т":"д",
  "ж":"ш", "ш":"ж",
  "з":"с", "с":"з"
 };

 const tasks = rows.map(function(row,index){

  const [source,checks,word,details] = row;

  const answers = Array.from(
   source.matchAll(/\{([а-яё]*)\}/gi)
  ).map(m => m[1]);

  const pattern = source.replace(
   /\{[а-яё]*\}/gi,"{}"
  );

  const fullWord = source.replace(/[{}]/g,"");

  const checkList = (checks || "").split("|");
  const detailList = (details || "").split("|");

  const dictionaryWord =
   word || fullWord.toLowerCase();

  const blanks = answers.map(function(answer,i){

   const checkWord = checkList[i] || "";
   const detail = detailList[i] || "";

   let options;

   if(answer === ""){
    options = ["т","д","в","л","с",""];
   } else if(pairs[answer]){
    options = [answer,pairs[answer],""];
   } else {
    options = [answer,"т","д","с","в","л",""];
   }

   options = [...new Set(options)];

   options.sort(function(a,b){
    if(a === "") return 1;
    if(b === "") return -1;
    return a.localeCompare(b,"ru");
   });

   let ruleId = "consonants";

   let explanation =
    "Правильно: " + fullWord + ". ";

   if(answer === ""){

    ruleId = "consonants-empty";

    explanation +=
     "Дополнительная согласная не пишется.";

   } else {

    explanation +=
     "Пишется " + answer.toUpperCase() + ".";

    if(!checkWord){
     ruleId = "consonants-dictionary";
    }

   }

   if(checkWord){

    explanation +=
     " Проверочное слово: " + checkWord + ".";

   } else if(!detail){

    explanation +=
     " Написание необходимо запомнить.";

   }

   if(detail){
    explanation += " " + detail;
   }

   return {

    answer: answer,
    options: options,
    rule: ruleId,
    name: window.ORTHO_RULES[ruleId].title,
    explanation: explanation,
    checkWord: checkWord

   };

  });

  const links = [{

   label: dictionaryWord + " — Викисловарь",

   url: "https://ru.wiktionary.org/wiki/" +
    encodeURIComponent(dictionaryWord),

   note: "Проверка написания"

  }];

  checkList.filter(Boolean).forEach(function(check){

   links.push({

    label: check + " — Викисловарь",

    url: "https://ru.wiktionary.org/wiki/" +
     encodeURIComponent(check),

    note: "Проверочное слово"

   });

  });

  return {

   id: "alexandrova-04-" +
    String(exercise).padStart(3,"0") + "-" +
    String(index+1).padStart(3,"0"),

   topic: "consonants",

   exercise: exercise,

   pattern: pattern,

   instruction:
    "Вставьте согласную, если она необходима. Если буква не нужна, выберите пустой вариант.",

   blanks: blanks,

   links: links

  };

 });

 const existingIds = new Set(
  window.ORTHO_DATA.map(task => task.id)
 );

 window.ORTHO_DATA.push(
  ...tasks.filter(task => !existingIds.has(task.id))
 );

};

