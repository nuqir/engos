window.addNounendExercise = function(exercise, rows){

 const tasks = rows.map(function(row,index){

  const [source,codes,lemmas,details] = row;

  const answers = Array.from(
   source.matchAll(/\{([а-яё]+)\}/gi)
  ).map(m => m[1]);

  const pattern = source.replace(
   /\{[а-яё]+\}/gi,"{}"
  );

  const fullWord = source.replace(/[{}]/g,"");

  const ruleList = codes.split("|");
  const lemmaList = lemmas.split("|");
  const detailList = (details || "").split("|");

  if(
   answers.length !== ruleList.length ||
   answers.length !== lemmaList.length
  ){
   throw new Error(
    "Ошибка количества пропусков: " + source
   );
  }

  const blanks = answers.map(function(answer,i){

   const code = ruleList[i];
   const rule = window.NOUNEND_RULES[code];

   if(!rule){
    throw new Error("Неизвестное правило: " + code);
   }

   let options;

   if(["F","G"].includes(code)){
    options = ["о","ы"];
   } else if(["T1","T2","TE","FF"].includes(code)){
    options = ["о","е","ы"];
   } else if(["KA","KO","ISH","LA","N"].includes(code)){
    options = ["а","о","е","и"];
   } else if(["R1","D1","P1","P2","R3","D3","P3","IA","IE","IY","YE","MYA"].includes(code)){
    options = ["е","и","ы"];
   } else {
    options = ["а","о","е","и","ы","я","ю"];
   }

   if(!options.includes(answer)){
    options.push(answer);
   }

   return {

    answer: answer,
    options: options,

    rule: "nounend-" + code,
    name: rule.title,

    explanation:
     "Правильно: " + fullWord + ". " +
     "Начальная форма: " + lemmaList[i] + ". " +
     "Пишется буква " + answer.toUpperCase() + ". " +
     rule.text + " " +
     (detailList[i] || ""),

    checkWord: ""

   };

  });

  const links = [...new Set(lemmaList)].map(word => ({

   label: word + " — Викисловарь",

   url: "https://ru.wiktionary.org/wiki/" +
    encodeURIComponent(word),

   note: "Начальная форма, склонение и падежные окончания"

  }));

  return {

   id: "alexandrova-10-" +
    String(exercise).padStart(3,"0") + "-" +
    String(index+1).padStart(3,"0"),

   topic: "nounend",
   exercise: exercise,
   pattern: pattern,

   instruction:
    "Вставьте пропущенные буквы. Определите склонение и падеж существительного.",

   blanks: blanks,
   links: links

  };

 });

 const existingIds = new Set(
  window.ORTHO_DATA.map(t => t.id)
 );

 window.ORTHO_DATA.push(
  ...tasks.filter(t => !existingIds.has(t.id))
 );

};


