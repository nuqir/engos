window.addSibilantsExercise = function(exercise, rows){

 const tasks = rows.map(function(row,index){

  const [source,codes,details] = row;

  const answers = Array.from(
   source.matchAll(/\{([а-яё]+)\}/gi)
  ).map(m => m[1]);

  const pattern = source.replace(
   /\{[а-яё]+\}/gi,"{}"
  );

  const fullWord = source.replace(/[{}]/g,"");

  const ruleList = codes.split("|");
  const detailList = (details || "").split("|");

  if(answers.length !== ruleList.length){
   throw new Error(
    "Ошибка количества пропусков: " + source
   );
  }

  const blanks = answers.map(function(answer,i){

   const code = ruleList[i];
   const rule = window.SIBILANT_RULES[code];

   if(!rule){
    throw new Error("Неизвестное правило: " + code);
   }

   let options;

   if(["а","я"].includes(answer)){
    options = ["а","я"];
   } else if(["у","ю"].includes(answer)){
    options = ["у","ю"];
   } else if(["и","ы"].includes(answer)){
    options = ["и","ы"];
   } else if(["о","ё","е"].includes(answer)){
    options = ["о","ё","е"];
   } else {
    options = ["а","о","е","ё","и","ы","у","ю","я"];
   }

   return {

    answer: answer,
    options: options,

    rule: "sibilant-" + code,
    name: rule.title,

    explanation:
     "Правильно: " + fullWord + ". " +
     "Пишется " + answer.toUpperCase() + ". " +
     rule.text + " " +
     (detailList[i] || ""),

    checkWord: ""

   };

  });

  const words = Array.from(
   source.matchAll(/[а-яё{}-]+/gi)
  )
  .map(m => m[0])
  .filter(word => word.includes("{"))
  .map(word =>
   word.replace(/[{}]/g,"").toLowerCase()
  );

  const links = [...new Set(words)].map(word => ({

   label: word + " — Викисловарь",

   url: "https://ru.wiktionary.org/wiki/" +
    encodeURIComponent(word),

   note: "Проверка написания и значения"

  }));

  return {

   id: "alexandrova-08-" +
    String(exercise).padStart(3,"0") + "-" +
    String(index+1).padStart(3,"0"),

   topic: "sibilants",
   exercise: exercise,
   pattern: pattern,

   instruction:
    "Вставьте пропущенные гласные после шипящих и Ц.",

   blanks: blanks,
   links: links

  };

 });

 const existingIds = new Set(
  window.ORTHO_DATA.map(t => t.id)
 );

 window.ORTHO_DATA.push(
  ...tasks.filter(t => !existingIds.has(t.id))
 );

};


