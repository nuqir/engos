function dictionary(word,note="Словарная проверка написания"){
 return {
  label:word+" — Викисловарь",
  url:"https://ru.wiktionary.org/wiki/"+encodeURIComponent(word),
  note
 };
}

function item(id,topic,exercise,pattern,answer,options,rule,name,explanation,word,checkWord=""){
 return {
  id,
  topic,
  exercise,
  pattern,
  blanks:[{
   answer,
   options,
   rule,
   name,
   explanation,
   checkWord
  }],
  links:[dictionary(word)]
 };
}

